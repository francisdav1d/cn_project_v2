'use strict';
/**
 * Builds dist/ARQBeam(.exe): ARQ Beam as one executable that runs on machines without Node.js,
 * using Node's Single Executable Applications (SEA).
 *
 *   npm run build        (or: node scripts/build-exe.js)
 *
 * 1. Bundle scripts/sea-entry.js, server.js and lib/*.js into one CommonJS file, because an SEA's
 *    main script can only require() Node's built-in modules.
 * 2. Generate the SEA blob, with every file in public/ embedded as an asset.
 * 3. Copy the node executable running this script into dist/ and inject the blob with postject
 *    (fetched by npx on first use; ARQ Beam itself still has no dependencies).
 *
 * The result runs on the OS and CPU it was built on (Windows x64 here); build on a Mac for a Mac.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const WORK = path.join(DIST, 'build');
const EXE = path.join(DIST, process.platform === 'win32' ? 'ARQBeam.exe' : 'ARQBeam');
const POSTJECT = 'postject@1.0.0-alpha.6';
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

function main() {
  const [major, minor] = process.versions.node.split('.').map(Number);
  if (major < 20 || (major === 20 && minor < 12)) fail(`Node ${process.version} is too old to build; use Node 20.12 or newer.`);
  if (process.config.variables.node_shared) fail('This node is built as a shared library and cannot become a standalone exe.');

  fs.rmSync(WORK, { recursive: true, force: true });
  fs.mkdirSync(WORK, { recursive: true });

  const bundlePath = path.join(WORK, 'arq-beam.js');
  const modules = bundle(path.join(ROOT, 'scripts', 'sea-entry.js'), bundlePath);
  const assets = {};
  for (const file of walk(path.join(ROOT, 'public'))) assets[rel(file)] = file;
  log(`bundled ${modules} modules, embedding ${Object.keys(assets).length} dashboard files`);

  const blob = path.join(WORK, 'sea-prep.blob');
  const config = path.join(WORK, 'sea-config.json');
  fs.writeFileSync(config, JSON.stringify({
    main: bundlePath, output: blob, assets,
    disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false,
  }, null, 2));
  execFileSync(process.execPath, ['--experimental-sea-config', config], { stdio: 'inherit' });

  try {
    fs.copyFileSync(process.execPath, EXE);
  } catch (err) {
    fail(err.code === 'EBUSY' || err.code === 'EPERM' ? `${rel(EXE)} is in use. Close ARQ Beam and build again.` : err.message);
  }
  removeSignature();
  log(`injecting into ${rel(EXE)} (node ${process.version})`);
  const args = [POSTJECT, rel(EXE), 'NODE_SEA_BLOB', rel(blob), '--sentinel-fuse', FUSE];
  if (process.platform === 'darwin') args.push('--macho-segment-name', 'NODE_SEA');
  run('npx', ['--yes', ...args]);
  if (process.platform === 'darwin') run('codesign', ['--sign', '-', rel(EXE)]);

  fs.rmSync(WORK, { recursive: true, force: true });
  log(`done: ${rel(EXE)} (${(fs.statSync(EXE).size / 1048576).toFixed(1)} MB)`);
}

/**
 * Minimal CommonJS bundler for this project: follows relative require() calls from the entry and
 * wraps each module in a function. Anything else (fs, node:sea, ...) goes to Node's require.
 */
function bundle(entry, out) {
  const list = [];
  const ids = new Map();
  const add = (file) => {
    if (ids.has(file)) return ids.get(file);
    const id = list.length;
    ids.set(file, id);
    list.push(null);
    const src = fs.readFileSync(file, 'utf8').replace(/^#!.*/, '');
    const deps = {};
    for (const [, spec] of src.matchAll(/\brequire\(\s*['"](\.{1,2}\/[^'"]+)['"]\s*\)/g)) {
      deps[spec] = add(resolve(path.dirname(file), spec));
    }
    list[id] = { file, src, deps };
    return id;
  };
  add(entry);

  const parts = list.map((m) => `// ${rel(m.file)}\n[function (module, exports, require, __filename, __dirname) {\n${m.src}\n}, ` +
    `${JSON.stringify(m.deps)}, ${JSON.stringify(rel(m.file))}]`);
  fs.writeFileSync(out, `'use strict';
// Generated by scripts/build-exe.js from the files named below. Do not edit.
const nodeRequire = require;
const nodePath = require('path');
const root = nodePath.dirname(process.execPath);
const cache = [];
const modules = [
${parts.join(',\n')}
];
function load(id) {
  if (cache[id]) return cache[id].exports;
  const [fn, deps, file] = modules[id];
  const module = { exports: {} };
  cache[id] = module;
  const filename = nodePath.join(root, file);
  const localRequire = (spec) => (spec in deps ? load(deps[spec]) : nodeRequire(spec));
  fn.call(module.exports, module, module.exports, localRequire, filename, nodePath.dirname(filename));
  return module.exports;
}
load(0);
`);
  return list.length;
}

function resolve(dir, spec) {
  const base = path.resolve(dir, spec);
  for (const file of [base, `${base}.js`, path.join(base, 'index.js')]) {
    if (fs.existsSync(file) && fs.statSync(file).isFile()) return file;
  }
  return fail(`Cannot resolve ${spec} from ${rel(dir)}`);
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

/** The copied node.exe is signed; injecting invalidates that, so drop it when the tool exists. */
function removeSignature() {
  if (process.platform === 'darwin') run('codesign', ['--remove-signature', rel(EXE)]);
  if (process.platform !== 'win32') return;
  const probe = spawnSync(`signtool remove /s ${rel(EXE)}`, { cwd: ROOT, stdio: 'ignore', shell: true });
  if (probe.status !== 0) log('signtool not found, leaving the (now invalid) node signature in place');
}

/** Runs a command from the project root. npx is a .cmd script on Windows, so this goes through a shell. */
function run(cmd, args) {
  const line = [cmd, ...args.map((a) => (/\s/.test(a) ? `"${a}"` : a))].join(' ');
  const r = spawnSync(line, { cwd: ROOT, stdio: 'inherit', shell: true });
  if (r.status !== 0) fail(`${cmd} ${args[0]} failed${r.error ? `: ${r.error.message}` : ''}`);
}

function rel(file) {
  return path.relative(ROOT, file).split(path.sep).join('/');
}

function log(msg) {
  console.log(`  build  ${msg}`);
}

function fail(msg) {
  console.error(`\n  build failed: ${msg}\n`);
  process.exit(1);
}

main();
